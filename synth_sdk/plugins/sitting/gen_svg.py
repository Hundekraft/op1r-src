#!/usr/bin/env python3
"""Generate lucierroom.svg + sitting_geom.h (screen of the "in a room" FX, Lucier's "I am sitting in a room").

Static line art only: the ends of the tape lane (the loop waveform fills it), and the four knob tracks (blue size,
green shape, white erosion, orange mix: each in a dim shade of its colour, the value is drawn over it). Everything
else is drawn by code (sitting.c): the "GEN 07" counter (stroke font) with the loop length / ARMED tags, shape name /
dimensions / loudest mode, the floor plan (L x W, blue) with the standing-wave nodal lines of the active axial modes
lighting up with their resonator, a side section for the height modes, the loop waveform (128 min / max buckets)
with the play head and beat / bar ticks, the knob labels and fills.
Never name it after a stock content/display file (checked: no lucierroom.svg in R246).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY = '#6F7173'
TRACK = ('#1A3557', '#004F32', '#4A4A4A', '#57141F')        # dim blue, green, white, red (~1/3)

GEN_X, GEN_Y, GEN_S = 16, 9, 2816                           # "GEN 07": top-left, scale Q10 px per font unit (16.5 px)
TAG_X, TAG_Y, TAG_S = 121, (8, 20), 1536                    # loop length / ARMED tags (9 px)
INFO_X, INFO_Y, INFO_S = 16, (36, 48, 60), 1536             # three info lines (shape, dims, loudest mode)
PLAN_CX, PLAN_CY, PLAN_W, PLAN_H = 234, 40, 100, 56         # floor plan box (the room at max size fills it)
SECT_X = 297                                                # side section (height) at the right of the plan
WAVE_X0, WAVE_X1, WAVE_Y, WAVE_H = 16, 304, 90, 12          # lane: the loop over 288 px, +-12 px; ticks below
LABEL_Y, LABEL_S = 115, 1536                                # knob labels (9 px)
KNOB_Y, KNOB_X, KNOB_W, KNOB_T = 133, (16, 91, 166, 241), 63, 5   # knob tracks (5 px thick)


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by plugins/sitting/gen_svg.py - lane ends + knob tracks; the rest is drawn by code -->']
    ln = lambda x1, y1, x2, y2, c=GREY, w=1: o.append(
        f'<line fill="none" stroke="{c}" stroke-width="{w}" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for x in (WAVE_X0, WAVE_X1):                           # tape lane ends
        ln(x, WAVE_Y - WAVE_H - 3, x, WAVE_Y + WAVE_H + 3)
    for x, c in zip(KNOB_X, TRACK):                        # knob tracks
        ln(x, KNOB_Y, x + KNOB_W, KNOB_Y, c, KNOB_T)
    o.append('</svg>')
    return '\n'.join(o) + '\n'


def header():
    d = lambda k, v: f'#define SG_{k} {v}'
    return '\n'.join([
        '/* generated by plugins/sitting/gen_svg.py - geometry of lucierroom.svg */',
        d('GEN_X', GEN_X), d('GEN_Y', GEN_Y), d('GEN_S', GEN_S),
        d('TAG_X', TAG_X), d('TAG_S', TAG_S), 'static const int16_t sg_tag_y[2] = { %d, %d };' % TAG_Y,
        d('INFO_X', INFO_X), d('INFO_S', INFO_S), 'static const int16_t sg_info_y[3] = { %d, %d, %d };' % INFO_Y,
        d('PLAN_CX', PLAN_CX), d('PLAN_CY', PLAN_CY), d('PLAN_W', PLAN_W), d('PLAN_H', PLAN_H), d('SECT_X', SECT_X),
        d('WAVE_X0', WAVE_X0), d('WAVE_X1', WAVE_X1), d('WAVE_Y', WAVE_Y), d('WAVE_H', WAVE_H),
        d('LABEL_Y', LABEL_Y), d('LABEL_S', LABEL_S),
        d('KNOB_Y', KNOB_Y), d('KNOB_W', KNOB_W), d('KNOB_T', KNOB_T * 1024),
        'static const int16_t sg_knob_x[4] = { ' + ', '.join(map(str, KNOB_X)) + ' };']) + '\n'


if __name__ == '__main__':
    open(os.path.join(HERE, 'lucierroom.svg'), 'w', newline='\n').write(svg())
    open(os.path.join(HERE, 'sitting_geom.h'), 'w', newline='\n').write(header())
    print('ok')
