#!/usr/bin/env python3
"""Write reed_params.h (fixed-point constants of reedophone.c) from a fit of the float prototype.

    python3 gen_params.py [tools/fits/<tag>.json]

The fit (tools/fit.py on tools/proto.c) gives the physical parameters in floating point; this converts them to the
integer formats reedophone.c uses. Run it after every refit, then rebuild.
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SR = 44100.0


def q(v, bits): return int(round(v * (1 << bits)))


def onepole(t, n=128):                            # smoothing coefficient per n samples, time constant t (s)
    return math.exp(-n / (t * SR))


def biquad_peak(fc, db, qq):
    A = 10 ** (db / 40); w = 2 * math.pi * fc / SR; al = math.sin(w) / (2 * qq); c = math.cos(w); a0 = 1 + al / A
    return [(1 + al * A) / a0, -2 * c / a0, (1 - al * A) / a0, -2 * c / a0, (1 - al / A) / a0]


def biquad_lp(fc, qq):
    w = 2 * math.pi * fc / SR; al = math.sin(w) / (2 * qq); c = math.cos(w); a0 = 1 + al
    return [(1 - c) / 2 / a0, (1 - c) / a0, (1 - c) / 2 / a0, -2 * c / a0, (1 - al) / a0]


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, 'tools', 'fits', 'final.json')
    p = json.load(open(src))['params']
    g = lambda k, d=None: float(p.get(k, d))
    L = ['/* generated by gen_params.py from %s: do not edit */' % os.path.basename(src), '#ifndef REED_PARAMS_H', '#define REED_PARAMS_H', '']
    def c(name, val, comment=''):
        L.append(f'#define {name:<14s} {val}' + (f'    /* {comment} */' if comment else ''))
    # reed: x(n) = b1 p(n-1) + a1 x(n-1) + a2 x(n-2), Q14
    wr = 2 * math.pi * g('fr'); T = 1 / SR; A = 1 / (wr * wr * T * T); B = g('qr') / (2 * wr * T)
    c('REED_B1', q(1 / (A + B), 14), f"reed {g('fr'):.0f} Hz, q {g('qr'):.3f}")
    c('REED_A1', q((2 * A - 1) / (A + B), 14)); c('REED_A2', q(-(A - B) / (A + B), 14))
    c('ZETA_Q15', q(g('zeta'), 15), f"embouchure: {g('zeta'):.4f} (the fit's low register; no register vent)")
    c('ZSLOPE', q(g('zslope', 0), 15), 'zeta change per octave above midi 70')
    c('FC_HZ', int(round(g('fc'))), 'bore end reflection low-pass')
    c('FCK_Q8', q(g('fck', 0), 8), 'cutoff floor, multiple of f0')
    loss = g('loss'); lk = g('loss_k')
    c('LOSS_Q15', q(loss, 15), f'loop loss at 261.6 Hz (exponent {lk:.3f})')
    c('LOSS_K_Q12', q(lk, 12))
    c('D_P_Q13', q(g('d_p'), 13), 'pressure above threshold at dynamics 0'); c('D_F_Q13', q(g('d_f'), 13), 'at dynamics 1')
    # attack: the fitted breath swell (att_p .. att) is not used on the device any more; the stock envelope sets it
    c('ATT2_B30', q(onepole(g('att2')), 30) if g('att2', 0) > 0 else 0, f"2nd breath stage {g('att2', 0) * 1000:.1f} ms")
    c('REL_B30', q(onepole(g('rel')), 30), f"release {g('rel') * 1000:.0f} ms")
    # dynamics curve dyn^vcurve, 33 points over dyn 0..1 (Q15), plus 8 points beyond 1 (to 1.25)
    vc = g('vcurve')
    L.append('static const int16_t DYN_POW[41] = { ' + ', '.join(str(min(32767, q((i / 32) ** vc, 15) // 2)) for i in range(41)) + ' };   /* (i/32)^%.3f, Q14 */' % vc)
    c('NOISE_Q15', q(g('noise'), 15), 'breath noise')
    tf = g('tongue', 0); tp = g('tongue_p', -1); tp = tf if tp < 0 else tp
    c('TONGUE_F_SMP', int(round(tf * SR)), f'tongue hold at full dynamics ({tf * 1000:.1f} ms)'); c('TONGUE_P_SMP', int(round(tp * SR)), f'at dynamics 0 ({tp * 1000:.1f} ms)')
    c('RADHP_Q15', q(math.exp(-2 * math.pi * g('rad_hp') / SR), 15), f"radiation high-pass {g('rad_hp'):.0f} Hz")
    eq = biquad_peak(g('eq_f'), g('eq_g'), g('eq_q')) if g('eq_f', 0) > 0 else [1, 0, 0, 0, 0]
    L.append('static const int32_t EQ_C[5] = { ' + ', '.join(str(q(v, 14)) for v in eq) + ' };   /* peak %.0f Hz %.1f dB q %.2f: b0 b1 b2 a1 a2, Q14 */' % (g('eq_f', 0), g('eq_g', 0), g('eq_q', 1)))
    lp = biquad_lp(g('olp'), g('olp_q')) if g('olp', 0) > 0 else [1, 0, 0, 0, 0]
    L.append('static const int32_t OLP_C[5] = { ' + ', '.join(str(q(v, 14)) for v in lp) + ' };   /* low-pass %.0f Hz q %.2f, Q14 */' % (g('olp', 0), g('olp_q', 0.707)))
    c('OUT_GAIN', int(g('out_gain', 4000)), 'output gain, Q8')
    for nm, vals in (('EQ', eq), ('OLP', lp)):
        assert all(abs(q(v, 14)) < 32768 for v in vals), f'{nm} coefficient beyond Q14 range (m16 operand)'
    L += ['', '#endif', '']
    sq = [int(round(math.sqrt(i * 2 ** 24))) - 32768 for i in range(64, 257)]
    NL = chr(10)
    open(os.path.join(HERE, 'reed_sqrt.h'), 'w').write('/* generated by gen_params.py: sqrt(i 2^24) - 32768, i = 64..256 */' + NL
        + (',' + NL).join(', '.join(str(v) for v in sq[j:j + 16]) for j in range(0, len(sq), 16)) + NL)
    sd = []                                       # sample-loop sqrt: a | (next - a) << 16, a = sqrt(i 2^24), i = 64..255
    for i in range(64, 256):
        a0 = int(round(math.sqrt(i * 2 ** 24))); a1 = int(round(math.sqrt((i + 1) * 2 ** 24)))
        sd.append(a0 | ((a1 - a0) << 16))
    open(os.path.join(HERE, 'reed_sqd.h'), 'w').write('/* generated by gen_params.py: sqrt(i 2^24) | (sqrt((i+1) 2^24) - sqrt(i 2^24)) << 16, i = 64..255 */' + NL
        + (',' + NL).join(', '.join('0x%08x' % v for v in sd[j:j + 8]) for j in range(0, len(sd), 8)) + NL)
    open(os.path.join(HERE, 'reed_params.h'), 'w').write('\n'.join(L))
    print('\n'.join(L))


if __name__ == '__main__':
    main()
