#!/usr/bin/env python3
"""Tune reedophone: measure the pitch of the real (fixed-point) engine over notes x dynamics and write the
error table reed_tune.h, which reedophone.c folds into its loop length. Iterates (the model is nonlinear).

    python3 calib.py [--iters 3] [--knobs b,g,w,r]

Dynamics j/4 (j = 0..5) are set with the breath knob at full velocity (the stock envelope is read doubled).
Notes that do not speak or jump to another mode get their neighbours' value.
"""
import argparse, os, subprocess, sys
import numpy as np, soundfile as sf
from concurrent.futures import ThreadPoolExecutor
from clar_common import f0_yin, hz_of, SR

HERE = os.path.dirname(os.path.abspath(__file__)); PLUG = os.path.dirname(HERE); SDK = os.path.dirname(os.path.dirname(PLUG))
M0, NM, ND = 20, 90, 6
EXE = os.path.join(HERE, 'rn_cal.exe'); TMP = os.path.join(os.environ.get('TEMP', '/tmp'), 'reed_cal'); os.makedirs(TMP, exist_ok=True)


def write_table(T):
    rows = ',\n'.join('{ ' + ', '.join(str(int(round(v))) for v in row) + ' }' for row in T)
    open(os.path.join(PLUG, 'reed_tune.h'), 'w').write(
        '/* generated by tools/calib.py: tuning error in cents x 16 (Q4), midi TUNE_M0.., dynamics 0, 1/4 .. 5/4 */\n'
        f'#define TUNE_M0 {M0}\n#define TUNE_NM {NM}\n#define TUNE_ND {ND}\n'
        'static const int16_t TUNE[TUNE_NM][TUNE_ND] = {\n' + rows + '\n};\n')


def build():
    subprocess.run(['gcc', '-O2', '-DOP1_HOST', '-DENGINE=ENGINE_reedophone', '-I', SDK, os.path.join(HERE, 'render_notes.c'),
                    os.path.join(PLUG, 'reedophone.c'), '-lm', '-o', EXE], check=True)


def measure(knobs):
    def one(ij):
        i, j = ij; m = M0 + i; dyn = j / 4
        k0 = min(32767, int(round(dyn * 26214 / 0.992)))
        p = os.path.join(TMP, f'c{i}_{j}.wav')
        subprocess.run([EXE, p, str(m), '127', '2.2', str(k0), *map(str, knobs[1:])], check=True)
        x = sf.read(p)[0]; seg = x[int(1.0 * SR):int(1.8 * SR)]
        if np.sqrt(np.mean(seg ** 2)) < 1e-4: return i, j, np.nan
        f = hz_of(m); fs = []
        for s in range(0, len(seg) - 4096, 4096):
            fs.append(f0_yin(seg[s:s + 4096], f * 0.75, f * 1.33))
        fe = np.median(fs); c = 1200 * np.log2(fe / f)
        if abs(c) > 150 or np.std(1200 * np.log2(np.array(fs) / fe)) > 10: return i, j, np.nan
        return i, j, c
    with ThreadPoolExecutor(18) as ex:
        res = list(ex.map(one, [(i, j) for i in range(NM) for j in range(ND)]))
    E = np.full((NM, ND), np.nan)
    for i, j, c in res: E[i, j] = c
    return E


def fill(E):
    E = E.copy()
    for j in range(ND):                                       # along pitch first
        col = E[:, j]; ok = ~np.isnan(col)
        if ok.sum() >= 2: E[:, j] = np.interp(np.arange(NM), np.where(ok)[0], col[ok])
        elif ok.sum() == 1: E[:, j] = col[ok][0]
    E[np.isnan(E)] = 0
    return E


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--iters', type=int, default=3); ap.add_argument('--knobs', default='26214,16384,16384,8192')
    ap.add_argument('--fresh', action='store_true', help='start from a zero table')
    a = ap.parse_args(); knobs = [int(v) for v in a.knobs.split(',')]
    T = np.zeros((NM, ND))
    if not a.fresh:
        import re
        txt = open(os.path.join(PLUG, 'reed_tune.h')).read()
        vals = [int(v) for v in re.findall(r'-?\d+', txt.split('= {', 1)[1])]
        if len(vals) == NM * ND: T = np.array(vals, float).reshape(NM, ND)
    for it in range(a.iters + 1):
        write_table(T); build(); E = measure(knobs)
        ok = ~np.isnan(E)
        print(f'iter {it}: measured |err| mean {np.nanmean(np.abs(E)):.2f} max {np.nanmax(np.abs(E)):.1f} cents, '
              f'{(~ok).sum()} of {E.size} unmeasured', flush=True)
        for j in range(ND):
            print(f'   dyn {j / 4:.2f}: ' + ' '.join('  .  ' if np.isnan(E[i, j]) else f'{E[i, j]:5.1f}' for i in range(0, NM, 6)))
        if it == a.iters: break
        T = T + 16 * fill(E)
        T = np.clip(T, -16 * 400, 16 * 400)
    write_table(T)


if __name__ == '__main__':
    main()
