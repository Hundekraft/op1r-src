#!/usr/bin/env python3
"""Generate palmediff.svg + palme_geom.h (screen geometry and DSP tables of the palme FX).

Screen: the Ondes Martenot "Palme" diffuseur - a palm-leaf soundboard with 12 strings fanning out from the
loudspeaker at its foot. Static parts here (leaf outline, ribs, speaker, bridge, string pins, dial ticks and
needles); strings, damper, gong rings, labels and the note name are drawn by palme.c.
Never name the SVG palme.svg / any stock content/display file.
"""
import math, os
HERE = os.path.dirname(os.path.abspath(__file__))
GREY, DGREY, LGREY = '#6F7173', '#3A3B3D', '#AEB1B3'
NS = 12
CX, CY = 160, 147                     # fan origin = loudspeaker centre
SPK_R = 9
BR_R = 22                             # bridge radius (strings start here)
DAMP_R = 31                           # damper felt radius
TH = 50.0                             # outer string angle, degrees
DIALS = [(260, 30, '#4D9EFF'), (298, 30, '#00ED95'), (260, 92, '#FFFFFF'), (298, 92, '#FF3A5D')]
DIAL_R = 10


def ang(i):  return math.radians(-TH + i * 2 * TH / (NS - 1))
def rtop(t): return 126 - 44 * (math.degrees(t) / TH) ** 2          # string length follows the leaf


def leaf_r(td):
    """leaf outline radius at angle td (degrees): pointed palm tip, rounded shoulders, closes at the foot"""
    a = abs(td)
    tip = 9 * max(0.0, 1 - a / 9) ** 1.5                              # pointed palm tip
    if a <= TH: return rtop(math.radians(a)) + 8 + tip
    if a >= 80: return 0
    return (rtop(math.radians(TH)) + 8) * math.cos((a - TH) / (80 - TH) * math.pi / 2) ** 0.6


def pt(r, t): return (CX + r * math.sin(t), CY - r * math.cos(t))


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by plugins/palme/gen_svg.py - Ondes Martenot Palme diffuseur. Strings, damper, gong,',
         '     labels and note name are drawn by palme.c -->']
    # leaf outline: polyline over the angle range, from the speaker's left side round to its right side
    pts = []
    for k in range(-78, 79, 2):
        r = max(leaf_r(k), SPK_R + 4)
        x, y = pt(r, math.radians(k))
        pts.append(f'{x:.1f},{y:.1f}')
    o.append(f'<polyline fill="none" stroke="{LGREY}" stroke-width="1.5" stroke-linejoin="round" points="{" ".join(pts)}"/>')
    # midrib (the palm), dark grey behind the strings
    o.append(f'<line fill="none" stroke="{DGREY}" stroke-width="1" x1="{CX}" y1="{CY - SPK_R - 2}" x2="{CX}" y2="{CY - 134}"/>')
    # bridge arc + loudspeaker
    pts = [pt(BR_R, math.radians(d)) for d in range(-56, 57, 4)]
    o.append('<polyline fill="none" stroke="#FFFFFF" stroke-width="1.5" points="' +
             ' '.join(f'{x:.1f},{y:.1f}' for x, y in pts) + '"/>')
    o.append(f'<circle fill="#000000" stroke="{LGREY}" stroke-width="1.5" cx="{CX}" cy="{CY}" r="{SPK_R}"/>')
    # string pins at the top
    for i in range(NS):
        x, y = pt(rtop(ang(i)), ang(i))
        o.append(f'<circle fill="{GREY}" cx="{x:.1f}" cy="{y:.1f}" r="1.3"/>')
    # dials: ticks at -135 / 0 / +135, coloured base dot, needle bar0..3 (rotated by code)
    for x, y, c in DIALS:
        for a in (-135, 0, 135):
            t = math.radians(a); s, co = math.sin(t), math.cos(t)
            p = lambda r: (round(x + r * s, 1), round(y - r * co, 1))
            (x1, y1), (x2, y2) = p(DIAL_R + 1), p(DIAL_R + 3)
            o.append(f'<line fill="none" stroke="{GREY}" stroke-width="2" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for i, (x, y, c) in enumerate(DIALS):
        o.append(f'<circle id="base{i}" fill="{c}" cx="{x}" cy="{y}" r="2.8"/>')
    for i, (x, y, c) in enumerate(DIALS):
        o.append(f'<line id="bar{i}" fill="none" stroke="{c}" stroke-width="2" x1="{x}" y1="{y}" x2="{x}" y2="{y - 9}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'


def header():
    q10 = lambda v: int(round(v * 1024))
    bot = [pt(BR_R, ang(i)) for i in range(NS)]
    top = [pt(rtop(ang(i)), ang(i)) for i in range(NS)]
    dmp = [pt(DAMP_R, ang(i)) for i in range(NS)]
    gong = [(1, 0), (1.73, 1), (2.33, 2), (3.91, 3), (4.11, 4), (6.30, 5), (6.71, 6), (7.34, 7),
            (1, 0, 14), (1.73, 1, -11), (2.33, 2, 9), (3.91, 3, -16)]           # 4 split (beating) twins, cents
    goff = [round(12 * math.log2(g[0]) * 256 + (g[2] / 100 * 256 if len(g) > 2 else 0)) for g in gong]
    P2 = [round(32768 * 2 ** (-k / 256)) for k in range(257)]
    P2D = [(P2[k] - P2[k + 1]) - (P2[k + 1] - P2[k + 2]) for k in range(255)] + [0]
    assert all(-1 <= d <= 2 for d in P2D)
    L = ['/* generated by plugins/palme/gen_svg.py - geometry of palmediff.svg + DSP tables */',
         f'#define PG_NS {NS}', f'#define PG_CX {CX}', f'#define PG_CY {CY}', f'#define PG_SPK_R {SPK_R}',
         '/* string end points (bridge, top pin) and damper contact, Q10 */',
         'static const int32_t pg_bot[PG_NS][2] = { ' + ', '.join(f'{{{q10(x)}, {q10(y)}}}' for x, y in bot) + ' };',
         'static const int32_t pg_top[PG_NS][2] = { ' + ', '.join(f'{{{q10(x)}, {q10(y)}}}' for x, y in top) + ' };',
         'static const int32_t pg_dmp[PG_NS][2] = { ' + ', '.join(f'{{{q10(x)}, {q10(y)}}}' for x, y in dmp) + ' };',
         '/* unit normal of each string (Q10, pointing to its right) */',
         'static const int16_t pg_nrm[PG_NS][2] = { ' + ', '.join(f'{{{q10(math.cos(ang(i)))}, {q10(math.sin(ang(i)))}}}' for i in range(NS)) + ' };',
         f'#define PG_GONG_X {CX}', f'#define PG_GONG_Y {CY - 74}',
         'static const int16_t pg_dial[4][2] = { ' + ', '.join(f'{{{x}, {y}}}' for x, y, _ in DIALS) + ' };',
         f'#define PG_DIAL_R {DIAL_R}',
         'static const uint8_t pg_dial_col[4][4] = { ' + ', '.join(
             '{ %d, %d, %d, 255 }' % tuple(int(c[i:i + 2], 16) for i in (1, 3, 5)) for _, _, c in DIALS) + ' };',
         '/* 2^(-k/256), Q15 (k = 0..256): exp2 for delay lengths and decay rates. Stored as the second differences of',
         ' * the rounded values (all in -1..2: 2 bits each, + 1, four per byte, lowest first; 450 bytes less code space);',
         ' * palme.c expands it into RAM (pm_pow2n[0] = 32768, first difference PM_POW2_D0) */',
         f'#define PM_POW2_D0 {P2[0] - P2[1]}',
         'static const uint8_t pm_pow2z[64] = { ' + ', '.join(str(sum((P2D[4 * i + j] + 1) << (2 * j) for j in range(4))) for i in range(64)) + ' };',
         '/* metallique: string -> plate mode (free circular plate ratios 1, 1.73, 2.33, 3.91, 4.11, 6.30, 6.71, 7.34,',
         ' * Fletcher & Rossing), strings 8..11 = split twins of modes 0..3 (+14, -11, +9, -16 cents: beating), Q8 semitones */',
         'static const int16_t pm_gong[PG_NS] = { ' + ', '.join(map(str, goff)) + ' };']
    return '\n'.join(L) + '\n'


if __name__ == '__main__':
    open(os.path.join(HERE, 'palmediff.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'palme_geom.h'), 'w').write(header())
    print('ok')
