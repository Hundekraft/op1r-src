#!/usr/bin/env python3
"""Generate mixtur.svg + mixtur_geom.h (shared geometry of the mixtur screen).

The undertone ladder: 24 horizontal strings hanging from a bridge on the left, string n has length 1/n (the
right ends trace the hyperbola of the undertone series; x is proportional to the undertone's frequency). Code
(mixtur.c) colours the four selected strings blue / green / white / red, ticks a bead down each of them once per
master period (n steps per divider cycle) and flashes the string when its divider wraps. Lower right, under the
hyperbola: the formant panel, a log-frequency axis 150 Hz .. 6 kHz on which code draws the two band-pass curves
(grey on page 1, blue / green on page 2). Bottom row: four readouts (undertone n, or F1 / F2 / resonance on page 2).
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
GREY, LIGHT, DARK = '#6F7173', '#DFD9FF', '#3A3B3E'
LX0, LY0, LDY, LMAX = 24, 9, 4.5, 284           # bridge x, string 1 y, spacing, length of string 1 (ends at 308)
FX0, FY, FPX = 150, 116, 30                      # formant panel: x of 150 Hz, baseline y, px per octave
FX1 = 310
FH = 54                                          # max curve height
COL_X = (46, 122, 198, 274)                      # readout column centres (blue, green, white, red)
CAP_Y, NUM_Y = 125, 134                          # caption / number top edges


def fx(f):
    return FX0 + FPX * math.log2(f / 150)


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by gen_svg.py - undertone ladder (strings 1/n) + formant axis; colours, beads, curves and',
         '     readouts are drawn by mixtur.c -->']
    for n in range(1, 25):
        y = LY0 + (n - 1) * LDY
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{LX0}" y1="{y:g}" x2="{LX0 + LMAX / n:.1f}" y2="{y:g}"/>')
    yb = LY0 + 23 * LDY
    o.append(f'<line fill="none" stroke="{LIGHT}" stroke-width="2" x1="{LX0 - 1}" y1="{LY0 - 4}" x2="{LX0 - 1}" y2="{yb + 4:g}"/>')
    # formant axis: baseline + ticks at 200 / 500 / 1k / 2k / 5k (taller at the decades)
    o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{FX0}" y1="{FY}" x2="{FX1}" y2="{FY}"/>')
    for f in (200, 300, 400, 500, 700, 1000, 1500, 2000, 3000, 4000, 5000):
        h = 4 if f in (500, 1000, 5000) else 2
        o.append(f'<line fill="none" stroke="{GREY}" stroke-width="1" x1="{fx(f):.1f}" y1="{FY + 1}" x2="{fx(f):.1f}" y2="{FY + 1 + h}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'


def header():
    h = ['/* generated by gen_svg.py - geometry of mixtur.svg */',
         f'#define MX_LX0 {LX0}', f'#define MX_LY0_Q10 {int(LY0 * 1024)}', f'#define MX_LDY_Q10 {int(LDY * 1024)}',
         f'#define MX_LMAX {LMAX}',
         f'#define MX_FX0 {FX0}', f'#define MX_FX1 {FX1}', f'#define MX_FY {FY}', f'#define MX_FPX {FPX}', f'#define MX_FH {FH}',
         f'#define MX_CAP_Y {CAP_Y}', f'#define MX_NUM_Y {NUM_Y}',
         '/* peak x (Q10) of the formants at page-2 word 0 and per full knob: F1 = 180 Hz * 2^(4.5 w), F2 = 500 Hz * 2^(3.5 w) */',
         f'#define MX_F1_X0_Q10 {int(round(fx(180) * 1024))}', f'#define MX_F1_SPAN_Q10 {int(round(4.5 * FPX * 1024))}',
         f'#define MX_F2_X0_Q10 {int(round(fx(500) * 1024))}', f'#define MX_F2_SPAN_Q10 {int(round(3.5 * FPX * 1024))}',
         'static const int16_t mx_col_x[4] = { ' + ', '.join(map(str, COL_X)) + ' };']
    return '\n'.join(h) + '\n'


if __name__ == '__main__':
    open(os.path.join(HERE, 'mixtur.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'mixtur_geom.h'), 'w').write(header())
    print('ok')
