#!/usr/bin/env python3
"""Generate warp_table.h for the brass synth engine: python3 gen_warp_table.py

Phase warp, for normalised phase x in [0, 1] and timbre t:
  y  = 2x - 1                                   # [-1, 1]
  y' = sign(y) * (exp(-t|y|) - 1) / (exp(-t) - 1)
  w  = 0.5 * y' + 0.5                           # back to [0, 1]

t = 0 is the identity (pure sine). As t grows the warped phase stays near 0 for the first half of the cycle and
near 1 for the second half, and the whole sine cycle is squeezed into a short burst around x = 0.5.

Tables written (Q15, 32768 = 1.0):
  warp_half[33][65]: rows s = 0..32 (x = s/64), columns 0..64 (t = 0..MAX_TIMBRE). The warp is point-symmetric,
                     w(1 - x) = 1 - w(x), so rows 33..64 are 32768 - warp_half[64 - s] (brass.c warp_row).
  warp_gain[65]:     level compensation per column, Q14. The warp keeps the peak at full scale but lowers the RMS
                     (by about 11 dB at the last column). The gain makes up LEVEL_COMP of that drop in dB: full
                     compensation would need about 3.5x gain and clip, and a brighter tone already sounds louder
                     at equal RMS.
"""
import math
import os

ROWS = 64            # phase resolution of the full cycle (rows 0..64, 64 = end of the cycle)
COLUMNS = 64         # timbre steps (columns 0..64)
MAX_TIMBRE = 30
LEVEL_COMP = 0.5     # fraction of the RMS drop (in dB) made up by warp_gain
SUB = 64             # sub-steps per row for the RMS estimate


def warp(x, t):
    if t < 0.01:
        return x
    y = 2.0 * x - 1.0
    w = (math.exp(-t * abs(y)) - 1.0) / (math.exp(-t) - 1.0)
    return 0.5 * (-w if y < 0 else w) + 0.5


def q15(v):
    return int(round(max(0.0, min(1.0, v)) * 32768))


def rows_for(t):
    """The full 65 rows as brass.c sees them (half table mirrored)."""
    half = [q15(warp(s / ROWS, t)) for s in range(ROWS // 2 + 1)]
    return half + [32768 - half[ROWS - s] for s in range(ROWS // 2 + 1, ROWS + 1)]


def rms_for(t):
    """RMS of one cycle of sin(2 pi w) with w linearly interpolated between rows, as the engine plays it."""
    r = rows_for(t)
    acc = 0.0
    for s in range(ROWS):
        for k in range(SUB):
            w = r[s] + (r[s + 1] - r[s]) * k / SUB
            acc += math.sin(2 * math.pi * w / 32768) ** 2
    return math.sqrt(acc / (ROWS * SUB))


timbres = [c * MAX_TIMBRE / COLUMNS for c in range(COLUMNS + 1)]
rms0 = rms_for(0.0)
gains = [(rms0 / rms_for(t)) ** LEVEL_COMP for t in timbres]

out = ["/* generated by gen_warp_table.py - do not edit */",
       "/* warp_half[s][c]: Q15 warped phase (32768 = 1.0) at phase s/64 (s = 0..32; rows 33..64 mirror: brass.c warp_row),",
       " * timbre column c = 0..64 (t = 0..%d) */" % MAX_TIMBRE,
       "static const int16_t warp_half[%d][%d] = {" % (ROWS // 2 + 1, COLUMNS + 1)]
for s in range(ROWS // 2 + 1):
    vals = [q15(warp(s / ROWS, t)) for t in timbres]
    out.append("    { /* s=%d */" % s)
    for i in range(0, len(vals), 13):
        out.append("        " + ", ".join("%5d" % v for v in vals[i:i + 13]) + ",")
    out.append("    },")
out.append("};")
out.append("")
out.append("/* warp_gain[c]: level compensation per timbre column, Q14 (16384 = 1.0), %.0f%% of the RMS drop in dB */"
           % (LEVEL_COMP * 100))
out.append("static const int16_t warp_gain[%d] = {" % (COLUMNS + 1))
g = [int(round(v * 16384)) for v in gains]
for i in range(0, len(g), 13):
    out.append("    " + ", ".join("%5d" % v for v in g[i:i + 13]) + ",")
out.append("};")

path = os.path.join(os.path.dirname(os.path.abspath(__file__)), "warp_table.h")
with open(path, "w", encoding="ascii", newline="\n") as f:     # written here, not via a shell redirect (encoding)
    f.write("\n".join(out) + "\n")
print("wrote %s (max gain %.2fx)" % (path, max(gains)))
