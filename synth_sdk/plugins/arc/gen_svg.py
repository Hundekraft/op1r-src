#!/usr/bin/env python3
"""Generate duddell.svg + arc_geom.h for the arc engine screen.

Static parts only: the two lamp-holder clamps at the outer ends of the carbons and four iter-style dials
(blue mu, green carbon, white hiss, red strike; bar0..3 rotated by code). Everything alive is drawn by arc.c with
raster lines on top: the phase portrait (x vs v of the most recent voice, a comet trail from the render's trace
ring), the two carbon rods (drawn after the portrait so the loop passes behind them), the arc between the tips
(size / flicker = output level, jaggedness = hiss), carbon glow on the tips (positive tip cratered with carbon),
red strike sparks, the 2nd lamp's portrait in green and its ratio.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
GREY, LIGHT = '#6F7173', '#DFD9FF'
CX, CY = 160, 62                      # arc gap centre = portrait centre
ROD_H = 5                              # rod half height
L_X0, L_TIP = 36, 151                  # left (positive) carbon: holder end .. tip
R_TIP, R_X0 = 169, 284                 # right (negative) carbon
DIAL_Y = 140
DIALS = [(70, '#4D9EFF'), (130, '#00ED95'), (190, '#FFFFFF'), (250, '#FF3A5D')]


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by plugins/arc/gen_svg.py - Duddell arc lamp; portrait, carbons, arc drawn by code -->']
    st = f'fill="none" stroke="{GREY}" stroke-width="1.5" stroke-linecap="butt"'
    # clamps: a C-bracket around each carbon's outer end, and a short stem down to the base line
    for x, d in ((L_X0, -1), (R_X0, 1)):
        a, b = x - 4 * d, x + 6 * d
        o.append(f'<path {st} d="M{b},{CY - ROD_H - 3}L{a},{CY - ROD_H - 3}L{a},{CY + ROD_H + 3}L{b},{CY + ROD_H + 3}"/>')
        o.append(f'<line {st} x1="{x + d}" y1="{CY + ROD_H + 3}" x2="{x + d}" y2="{CY + 34}"/>')
        o.append(f'<line {st} x1="{x + d - 6}" y1="{CY + 34}" x2="{x + d + 6}" y2="{CY + 34}"/>')
    # dials
    for x, c in DIALS:
        for a in (-135, 0, 135):
            t = math.radians(a); s, co = math.sin(t), math.cos(t)
            p = lambda rr: (round(x + rr * s, 1), round(DIAL_Y - rr * co, 1))
            (x1, y1), (x2, y2) = p(11), p(13)
            o.append(f'<line fill="none" stroke="{GREY}" stroke-width="2" stroke-linecap="square" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<circle id="base{i}" fill="{c}" cx="{x}" cy="{DIAL_Y}" r="2.8"/>')
    for i, (x, c) in enumerate(DIALS):
        o.append(f'<line id="bar{i}" fill="none" stroke="{c}" stroke-width="2" stroke-linecap="square" x1="{x}" y1="{DIAL_Y}" x2="{x}" y2="{DIAL_Y - 9}"/>')
    o.append('</svg>')
    return '\n'.join(o) + '\n'


def geom():
    g = ['/* generated by gen_svg.py - geometry of duddell.svg */',
         f'#define AG_CX {CX}', f'#define AG_CY {CY}', f'#define AG_ROD_H {ROD_H}',
         f'#define AG_L_X0 {L_X0}', f'#define AG_L_TIP {L_TIP}', f'#define AG_R_TIP {R_TIP}', f'#define AG_R_X0 {R_X0}',
         f'#define AG_DIAL_Y {DIAL_Y}',
         'static const int16_t ag_dial_x[4] = { ' + ', '.join(str(x) for x, _ in DIALS) + ' };']
    return '\n'.join(g) + '\n'


if __name__ == '__main__':
    open(os.path.join(HERE, 'duddell.svg'), 'w', newline='\n').write(svg())
    open(os.path.join(HERE, 'arc_geom.h'), 'w', newline='\n').write(geom())
    print('wrote duddell.svg, arc_geom.h')
