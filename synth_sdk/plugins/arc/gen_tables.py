#!/usr/bin/env python3
"""Generate arc_tables.h for plugins/arc.

  python gen_tables.py      # builds arc_calib.c + arc.c on the host (cc), measures G and loudness (~1 min)

ARC_GP[knob][pitch]: step factor G * 2 pi (Q12) so that the Van der Pol limit cycle of the *integer* engine
has exactly the played period. Rows = blue knob 0, 1024, .. 32767 (33), columns = pitch nodes every 1/8
octave from inc 2^19 (5.1 Hz) to 2^31 (22 kHz) (97), linear in inc inside each octave as arc.c interpolates.
It is stored losslessly compressed (ARC_GPZ, ~2.9 KB instead of 6.4 KB of code space): per row k (offset
ARC_GPROW[k]) the number n of stored nodes (the constant tail above the reachable range repeats node n - 1), then per
node p < n the 2-D residual g[k][p] - g[k][p-1] - g[k-1][p] + g[k-1][p-1] (missing neighbours = 0) as int8,
-128 = escape followed by the residual as int16 (low byte first). arc.c decodes it into RAM (gp_decode).
ARC_GAIN[knob]: loudness normalisation (Q12) from the measured RMS of x (equal RMS for every mu).
ARC_RW/ARC_RR: ratio knob breakpoints (word, ratio Q14) with flat detents at simple ratios.
"""
import math, os, subprocess, sys, tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
SDK = os.path.dirname(os.path.dirname(HERE))
KN, PN = 33, 97
LEVEL = 0.5                     # sine (x amplitude 2) peak in full scale before velocity


def ratio_breakpoints():
    det = [1/2, 2/3, 3/4, 1, 5/4, 4/3, 3/2, 5/3, 2]
    def word(r):                 # continuous map: 1..8192 -> 0.5..1, 8192..32767 -> 1..2 (log)
        lr = math.log2(r)
        return 1 + (lr + 1) * 8191 if lr <= 0 else 8192 + lr * 24575
    pts = []
    for r in det:
        w = word(r); hw = 280 if r < 1 else (420 if r > 1 else 600)
        a, b = max(1, round(w - hw)), min(32767, round(w + hw))
        q = round(r * 16384)
        pts += [(a, q), (b, q)]
    return pts


def calibrate():
    exe = os.path.join(tempfile.gettempdir(), 'arc_calib')
    subprocess.run(['cc', '-O2', '-DOP1_HOST', '-DARC_CALIB', '-I', SDK, os.path.join(HERE, 'arc_calib.c'),
                    os.path.join(HERE, 'arc.c'), '-lm', '-o', exe], check=True)
    out = subprocess.run([exe, str(KN), str(PN)], check=True, capture_output=True, text=True).stdout
    rows = [l.split() for l in out.strip().splitlines()]
    data = {'gp': [[0] * PN for _ in range(KN)], 'cents': [[0] * PN for _ in range(KN)], 'rms': [[0] * PN for _ in range(KN)]}
    for ki, pj, gp, c, rms in rows:
        ki, pj = int(ki), int(pj)
        data['gp'][ki][pj] = int(gp); data['cents'][ki][pj] = float(c); data['rms'][ki][pj] = float(rms)
    # nodes the engine cannot reach (h clamped at 0.9: above ~6 kHz) keep the last reachable value, so the
    # interpolation below them stays smooth and h simply saturates further up
    for ki in range(KN):
        for pj in range(1, PN):
            if abs(data['cents'][ki][pj]) > 5:
                data['gp'][ki][pj] = data['gp'][ki][pj - 1]
    return data


def encode(gp):
    """lossless: 2-D residuals as int8 with an int16 escape (see the docstring), row offsets"""
    s8 = lambda v: ((v & 0xff) ^ 0x80) - 0x80
    z, rows = [], []
    for k in range(KN):
        rows.append(len(z))
        n = PN
        while n > 1 and gp[k][n - 2] == gp[k][PN - 1]: n -= 1
        z.append(n)
        for p in range(n):
            r = gp[k][p] - (gp[k][p - 1] if p else 0) - (gp[k - 1][p] if k else 0) + (gp[k - 1][p - 1] if k and p else 0)
            if -128 < r < 128: z.append(r)
            else: assert -32768 <= r < 32768; z += [-128, s8(r), s8(r >> 8)]
    return z, rows


def write(data):
    pts = ratio_breakpoints()
    if data:
        gp = data['gp']
        # loudness: mean rms over the musical range (inc 2^21..2^27 ~ 20 Hz .. 1.4 kHz) per knob row
        gain = []
        for ki in range(KN):
            r = [data['rms'][ki][pj] for pj in range(16, 65)]
            gain.append(round(4096 * LEVEL * math.sqrt(2) / (sum(r) / len(r))))
    else:
        gp = [[25736] * PN for _ in range(KN)]
        gain = [round(4096 * LEVEL)] * KN
    emit(gp, gain, pts)


def emit(gp, gain, pts):
    z, rows = encode(gp)
    o = ['/* generated by gen_tables.py - do not edit (arc tuning / loudness / ratio tables) */',
         '#define ARC_OCT 12', f'#define ARC_PN {PN}', f'#define ARC_RN {len(pts)}',
         f'#define ARC_KN {KN}',
         '/* G * 2 pi, Q12: [blue knob / 1024][1/8 octave], compressed (gen_tables.py: encode) */',
         f'static const uint16_t ARC_GPROW[ARC_KN] = {{ ' + ', '.join(map(str, rows)) + ' };',
         f'static const int8_t ARC_GPZ[{len(z)}] = {{']
    for i in range(0, len(z), 32):
        o.append('    ' + ', '.join(str(v) for v in z[i:i + 32]) + ',')
    o.append('};')
    o.append(f'static const int16_t ARC_GAIN[{KN}] = {{ ' + ', '.join(map(str, gain)) + ' };   /* Q12 */')
    o.append('static const int16_t ARC_RW[ARC_RN] = { ' + ', '.join(str(w) for w, _ in pts) + ' };')
    o.append('static const uint16_t ARC_RR[ARC_RN] = { ' + ', '.join(str(r) for _, r in pts) + ' };   /* Q14 */')
    open(os.path.join(HERE, 'arc_tables.h'), 'w', newline='\n').write('\n'.join(o) + '\n')


if __name__ == '__main__':
    write(None)                  # placeholder header so arc.c builds for the calibration run
    d = calibrate()
    write(d)
    if d:
        worst = max(abs(c) for row in d['cents'] for c in row[:81])
        print(f'tables written; worst residual up to inc 2^29 (5.5 kHz): {worst:.2f} cents')
