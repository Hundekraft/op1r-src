#!/usr/bin/env python3
"""Generate display/oracle.svg + seq/oracle_geom.h (screen of the oracle sequencer, seq/oracle.c).

Static: the Shield chart's frame (thin grey lines): 8 cells (Daughters 4..1, Mothers 4..1, right to left as in the
manuscripts), 4 Nieces, 2 Witnesses, the Judge's cell and the Reconciler's small cell. Code draws the figures (dot
glyphs), the playhead, the Judge's name, the play state and the lanes. Visible area ends ~y 140 (as euclid.svg).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DIM = '#4A4C4E'
COLS = ['#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D']
GREY = '#6F7173'
TIER_H, ROW_DY, ROW0 = 35, 6, 8          # tier height, dot row pitch, first dot row below the tier top
JX0, JX1, RX1 = 124, 196, 232            # judge cell x, reconciler cell right edge (bottom tier)
NAME_X, LANE_X, STATE_X = 4, 238, 80   # judge name (left), lane notes (right), play state (HOLD / LATCH / EDIT)

def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by display/gen_oracle_svg.py - oracle sequencer: chart frame; figures and text drawn by code -->']
    L = lambda x1, y1, x2, y2: o.append(f'<line fill="none" stroke="{DIM}" stroke-width="1" x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}"/>')
    for t in range(1, 4):
        L(0, t * TIER_H - 0.5, 320, t * TIER_H - 0.5)
    for k in range(1, 8):
        L(k * 40 - 0.5, 2, k * 40 - 0.5, TIER_H - 3)
    for k in range(1, 4):
        L(k * 80 - 0.5, TIER_H + 2, k * 80 - 0.5, 2 * TIER_H - 3)
    L(159.5, 2 * TIER_H + 2, 159.5, 3 * TIER_H - 3)
    y0, y1 = 3 * TIER_H + 2, 4 * TIER_H + 2
    L(JX0 - 0.5, y0, JX0 - 0.5, y1); L(JX1 - 0.5, y0, JX1 - 0.5, y1); L(RX1 - 0.5, y0, RX1 - 0.5, y1)
    L(JX0 - 0.5, y1, RX1 - 0.5, y1)
    o.append('</svg>')
    return '\n'.join(o) + '\n'

def header():
    rgb = lambda c, f=1.0: '{ %d, %d, %d, 255 }' % tuple(int(int(c[i:i + 2], 16) * f) for i in (1, 3, 5))
    return '\n'.join(['/* generated by display/gen_oracle_svg.py - geometry of display/oracle.svg */',
        f'#define ORA_TIER_H {TIER_H}', f'#define ORA_ROW_DY {ROW_DY}', f'#define ORA_ROW0 {ROW0}',
        f'#define ORA_JX0 {JX0}', f'#define ORA_JX1 {JX1}', f'#define ORA_RX1 {RX1}',
        f'#define ORA_NAME_X {NAME_X}', f'#define ORA_LANE_X {LANE_X}', f'#define ORA_STATE_X {STATE_X}',
        'static const uint8_t ora_col[4][4] = { ' + ', '.join(rgb(c) for c in COLS) + ' };',
        'static const uint8_t ora_dimcol[4][4] = { ' + ', '.join(rgb(c, 0.4) for c in COLS) + ' };',
        'static const uint8_t ora_grey[4] = ' + rgb(GREY) + ';',
        'static const uint8_t ora_dim[4] = ' + rgb(GREY, 0.55) + ';',
        'static const uint8_t ora_green[4] = ' + rgb(COLS[1]) + ';',
        'static const uint8_t ora_white[4] = { 255, 255, 255, 255 };']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'oracle.svg'), 'w', newline='\n').write(svg())       # LF on Windows too
    open(os.path.join(os.path.dirname(HERE), 'seq', 'oracle_geom.h'), 'w', newline='\n').write(header())
    print('ok')
