#!/usr/bin/env python3
"""Generate display/peal.svg + seq/peal_geom.h (screen of the peal sequencer, seq/peal.c).

Static: a thin divider between the rows (left) and the info panel (right). Code draws the bell numbers, the treble's
blue line, lead-head lines and all text. Visible area ends ~y 140 (as euclid.svg).
"""
import os
HERE = os.path.dirname(os.path.abspath(__file__))
DIM = '#4A4C4E'
BLUE, GREEN, WHITE, RED, GREY = '#4D9EFF', '#00ED95', '#FFFFFF', '#FF3A5D', '#6F7173'
COL_X0, COL_DX, ROW_Y0, ROW_DY = 12, 22, 6, 14    # bell columns, rows (9 shown, newest at the bottom)
DIV_X, PANEL_X = 194, 204

def svg():
    return '\n'.join(['<?xml version="1.0" encoding="utf-8"?>',
        '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
        '\t width="320px" height="160px" viewBox="0 0 320 160">',
        '<!-- generated by display/gen_peal_svg.py - peal sequencer: divider; rows and text drawn by code -->',
        f'<line fill="none" stroke="{DIM}" stroke-width="1" x1="{DIV_X - 0.5}" y1="4" x2="{DIV_X - 0.5}" y2="136"/>',
        '</svg>']) + '\n'

def header():
    rgb = lambda c, f=1.0: '{ %d, %d, %d, 255 }' % tuple(int(int(c[i:i + 2], 16) * f) for i in (1, 3, 5))
    return '\n'.join(['/* generated by display/gen_peal_svg.py - geometry of display/peal.svg */',
        f'#define PL_COL_X0 {COL_X0}', f'#define PL_COL_DX {COL_DX}', f'#define PL_ROW_Y0 {ROW_Y0}', f'#define PL_ROW_DY {ROW_DY}',
        f'#define PL_PANEL_X {PANEL_X}',
        'static const uint8_t pl_blue[4] = ' + rgb(BLUE) + ';',
        'static const uint8_t pl_green[4] = ' + rgb(GREEN) + ';',
        'static const uint8_t pl_white[4] = ' + rgb(WHITE) + ';',
        'static const uint8_t pl_red[4] = ' + rgb(RED) + ';',
        'static const uint8_t pl_dimred[4] = ' + rgb(RED, 0.4) + ';',
        'static const uint8_t pl_grey[4] = ' + rgb(GREY, 1.4) + ';',
        'static const uint8_t pl_dim[4] = ' + rgb(GREY) + ';']) + '\n'

if __name__ == '__main__':
    open(os.path.join(HERE, 'peal.svg'), 'w', newline='\n').write(svg())         # LF on Windows too
    open(os.path.join(os.path.dirname(HERE), 'seq', 'peal_geom.h'), 'w', newline='\n').write(header())
    print('ok')
